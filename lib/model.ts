// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot can defend as a launch
// candidate: the whole 40-protocol watchlist (the floor, never the ceiling) plus
// every other pre-token protocol below the floor that is not a wrapped, staked
// or bridged product of a token that already trades. Protocols whose token
// already trades are kept apart, shown with their market cap, never mixed into
// the ranking.
//
// Implied value is derived from the snapshot's own figures, never from a list
// of names. The one number no snapshot row carries is the multiple a token
// trades at per dollar of TVL, so the model takes it from the snapshot itself:
// for each category, the median market-cap-to-TVL ratio of that category's
// live-token protocols (at least four of them); categories with too few live
// peers fall back to the median across all live-token protocols. The multiple
// is winsorised to [0.02, 1.50] so one outlier cannot set a category's price.
//
//   peer     = category median(mcap/tvl) of live peers, else global median
//   growth   = clamp(change_7d, -50, 100) per cent; missing growth counts as 0
//   growthM  = 1 + growth/100 x 0.6
//   maturity = 0.70 + 0.30 x min(age_days, 730)/730; unknown age counts as 365
//   reach    = 1 + 0.02 x min(chains, 5)
//   implied  = max(1, round(tvl_usd x peer x growthM x maturity x reach))
//
// Age is the time since DefiLlama first listed the protocol: how long it has
// run with no token. Growth is the TVL change over seven days. Reach counts
// the chains the protocol runs on, capped at five, as a small resilience term.
// Every factor is shown per row in the dashboard's detail view, so any reader
// can recompute the number from the snapshot figures.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

